"""Подозрительные признаки в тексте вакансии: только пометка, не отсев.

Вакансия остаётся в очереди, на карточке появляется предупреждение —
решение за человеком. Срабатывания возможны и у честных вакансий.
"""

from __future__ import annotations

import html
import re

_FLAGS = {
    "просят предоплату": re.compile(
        r"предоплат|оплат\w*\s+(?:обучени|курс|стажировк|доступ)|"
        r"(?:страхов|вступительн|гарантийн)\w*\s+(?:взнос|плат[её]ж)|внес\w*\s+депозит",
        re.I,
    ),
    "просят установить приложение": re.compile(
        r"установ\w*\s+(?:\w+\s+)?(?:приложени|программ|apk)|"
        r"скача\w*\s+(?:\w+\s+)?(?:приложени|клиент)|\.apk\b|testflight",
        re.I,
    ),
    "просят коды или доступы": re.compile(
        r"код\w*\s+из\s+(?:смс|sms)|(?:смс|sms)[- ]код|код\w*\s+подтверждени|"
        r"(?:переда|сообщи|пришли)\w*\s+(?:\w+\s+){0,2}(?:доступ|парол|логин)|"
        r"данн\w+\s+(?:банковск\w+\s+)?карт|\bcvv\b|apple\s?id|"
        r"(?:скан|фото)\w*\s+паспорт",
        re.I,
    ),
}
_TAG = re.compile(r"<[^>]+>")


def suspicious(text: object) -> list[str]:
    """Названия сработавших признаков (пустой список — чисто)."""
    plain = html.unescape(_TAG.sub(" ", str(text or "")))
    return [name for name, pattern in _FLAGS.items() if pattern.search(plain)]
