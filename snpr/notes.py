"""Пометки для человека: что стоит знать о вакансии до отклика.

В отличие от fraud.py это не подозрения, а условия найма. Вакансия не
отбрасывается и скор не меняется — на карточке появляется строка «ℹ️ …».
"""

from __future__ import annotations

import re

RU_ONLY = "работа только из России?"
TEST_TASK = "есть тестовое задание"

_RU_ONLY = re.compile(
    r"удал[её]нн?(?:о|ая работа|ый формат)?\s+(?:по|из|в)\s+(?:России|РФ)\b"
    r"|(?:работ\w*|находит\w*|прожива\w*|располож\w*)\s+(?:\w+\s+){0,2}на\s+территории\s+(?:РФ|России|Российской)"
    r"|на\s+территории\s+(?:РФ|России)\s+(?:обязательн|только)"
    r"|только\s+(?:в|из|по)\s+(?:РФ|России)\b"
    r"|(?:налогов\w+\s+)?резидент\w*\s+(?:РФ|России)\b"
    r"|(?:находиться|проживать|быть)\s+в\s+(?:РФ|России)\b",
    re.I,
)
_TEST_TASK = re.compile(
    r"тестов\w*\s+задани|тестовое\b|тестовую\s+задач|test\s+(?:task|assignment)|take[\s-]?home",
    re.I,
)


def notes(text: str) -> list[str]:
    found = []
    if _RU_ONLY.search(text):
        found.append(RU_ONLY)
    if _TEST_TASK.search(text):
        found.append(TEST_TASK)
    return found
